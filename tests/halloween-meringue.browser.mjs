// Run using the existing Playwright CLI against the disconnected AU localhost preview.
// Uses this isolated browser's cart only; never submits an order or contacts Appwrite.
async page => {
  page.setDefaultTimeout(8000)
  const origin = new URL(page.url()).origin
  if (!['localhost', '127.0.0.1'].includes(new URL(origin).hostname)) throw Error('LOCAL_PREVIEW_ONLY')
  const check = (ok, label) => { if (!ok) throw Error(label) }
  const errors = [], forbidden = []
  page.on('pageerror', e => errors.push(e.message))
  await page.unroute('**/*')
  await page.route('**/*', route => {
    const url = new URL(route.request().url())
    if (url.hostname === 'api.verygood-chocolate.com' || (url.pathname === '/appwrite' || url.pathname.startsWith('/appwrite/'))) {
      forbidden.push(url.pathname); return route.abort()
    }
    return route.continue()
  })
  await page.clock.install({ time: new Date('2026-10-28T00:00:00Z') })
  await page.evaluate(() => localStorage.clear())
  await page.goto(origin + '/')
  const dismiss = page.getByRole('button', { name: 'Dismiss announcement', exact: true })
  if (await dismiss.isVisible()) await dismiss.click()
  const consent = page.getByRole('button', { name: 'Essential only', exact: true })
  if (await consent.isVisible()) await consent.click()
  const section = page.getByRole('region', { name: 'Halloween Meringue Pops' })
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 900 })
    await section.scrollIntoViewIfNeeded()
    check(!(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)), `Home overflow ${width}`)
    await section.screenshot({ path: `output/playwright/meringue/home-${width}.png` })
  }
  await page.getByRole('link', { name: 'CHOOSE YOUR PACK', exact: true }).click()
  const packs = page.getByRole('group', { name: 'Choose your pack', exact: true })
  for (const [name, price] of [['Taster', '12.00'], ['Half dozen', '23.00'], ['Dozen', '45.00'], ['Double dozen', '85.00']]) {
    await packs.getByRole('button', { name: new RegExp('^' + name + ' ·') }).click()
    check((await page.locator('.au-pave-sticky-order').textContent()).includes(price), `Pack price ${name}`)
  }
  await packs.getByRole('button', { name: /^Half dozen ·/ }).click()
  await page.getByRole('button', { name: 'Quantity increase', exact: true }).click()
  await page.getByRole('button', { name: 'Photo 2', exact: true }).click()
  await page.screenshot({ path: 'output/playwright/meringue/detail-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Add to bag', exact: true }).first().click()
  await page.getByRole('link', { name: 'View bag', exact: true }).first().click()
  const bag = page.locator('.renewal-bag')
  check((await bag.textContent()).includes('12 pieces'), 'Two 6-packs physical quantity')
  check((await bag.textContent()).includes('AUD 46.00'), 'Two pack price')
  await page.getByRole('button', { name: 'Quantity decrease', exact: true }).click()
  check((await bag.textContent()).includes('AUD 23.00'), 'Quantity update')
  await page.getByRole('button', { name: /^Pickup date\./ }).click()
  check(await page.getByRole('button', { name: /^2026-10-29/ }).isDisabled(), 'Thursday blocked')
  await page.getByRole('button', { name: /^2026-10-30/ }).click()
  const times = page.getByRole('combobox', { name: 'Pickup time', exact: true })
  check((await times.locator('option').allTextContents()).at(-1) === '20:00', 'Friday closes 20:00')
  await page.getByRole('button', { name: /^Pickup date\./ }).click()
  await page.getByRole('button', { name: 'Next month', exact: true }).click()
  check(await page.getByRole('button', { name: /^2026-11-04/ }).isDisabled(), 'Post-season blocked')
  await page.getByRole('button', { name: /^2026-11-01/ }).click()
  check((await times.locator('option').allTextContents()).at(-1) === '13:00', 'Sunday closes 13:00')
  await times.selectOption('13:00')
  check(await page.getByRole('button', { name: 'Send request', exact: true }).isDisabled(), 'Preview never submits')
  await page.reload()
  check((await bag.textContent()).includes('AUD 23.00'), 'Cart persists on refresh')
  await page.goto(origin + '/cakes/pave-chocolate-cake')
  await page.getByRole('button', { name: 'Add to bag', exact: true }).first().click()
  await page.clock.setSystemTime(new Date('2026-10-31T01:59:59Z'))
  await page.goto(origin + '/cakes/halloween-meringue')
  check(!(await page.getByRole('button', { name: 'Add to bag', exact: true }).first().isDisabled()), 'Open immediately before deadline')
  await page.clock.runFor(1200)
  for (const button of await page.getByRole('button', { name: 'Add to bag', exact: true }).all()) check(await button.isDisabled(), 'Live cutoff disables all purchase buttons')
  await page.goto(origin + '/cart')
  await page.getByRole('alert').filter({ hasText: 'Halloween orders have closed' }).waitFor()
  check((await bag.textContent()).includes('Halloween Meringue Pops'), 'Expired cart preserved')
  check((await bag.textContent()).includes('Pavé Whole Cake'), 'Other cart product preserved')
  await bag.getByRole('listitem').filter({ hasText: 'Halloween Meringue Pops' }).getByRole('button', { name: /^Remove/ }).click()
  check(!(await bag.textContent()).includes('Halloween Meringue Pops'), 'Expired product removable')
  check((await bag.textContent()).includes('Pavé Whole Cake'), 'Removing seasonal product preserves cake')
  await page.goto(origin + '/')
  check(await page.locator('.au-meringue-season').count() === 0, 'Home hides after cutoff')
  await page.goto(origin + '/cakes')
  check(await page.locator('a[href="/cakes/halloween-meringue"]').count() === 0, 'Collection hides after cutoff')
  check(!errors.length, errors.join('\n'))
  check(!forbidden.length, 'Unexpected backend request')
  await page.clock.setSystemTime(new Date())
  await page.goto(origin + '/')
  return { packPrices: 'PASS', cart: 'PASS', pickup: 'PASS', liveCutoff: 'PASS', expiredCart: 'PASS', mobileAndDesktop: 'PASS', backendRequests: forbidden.length, pageErrors: errors }
}
