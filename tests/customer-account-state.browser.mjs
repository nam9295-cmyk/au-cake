async (page) => {
  const check=(condition,message)=>{if(!condition)throw Error(message)}
  const pageErrors=[]
  page.on('pageerror',error=>pageErrors.push(error.message))
  await page.route('**/*',route=>new URL(route.request().url()).hostname==='localhost'?route.continue():route.request().resourceType()==='stylesheet'?route.fulfill({contentType:'text/css',body:''}):route.abort())
  await page.goto('http://localhost:4173/tests/fixtures/customer-account/ui.html')
  await page.waitForFunction(()=>document.querySelector('#state')?.textContent==='guest')
  await page.evaluate(()=>window.customerAccountTest.reset({enabled:false}))
  await page.waitForFunction(()=>document.querySelector('#state')?.textContent==='guest')
  check((await page.evaluate(()=>window.customerAccountTest.counts())).calls===0,'disabled Account calls')
  await page.evaluate(()=>window.customerAccountTest.reset({ready:false}))
  await page.waitForFunction(()=>document.querySelector('#state')?.textContent==='unavailable')
  check((await page.evaluate(()=>window.customerAccountTest.counts())).calls===0,'unsafe health called Account')
  await page.click('#signin')
  await page.waitForSelector('dialog[open]')
  check(await page.getByRole('button',{name:'Continue with Google'}).isDisabled(),'unsafe Google enabled')
  check(await page.getByRole('button',{name:'Continue as Guest'}).isEnabled(),'guest blocked')
  await page.getByRole('button',{name:'Continue as Guest'}).click()
  await page.evaluate(()=>window.customerAccountTest.reset({mode:'pending'}))
  await page.click('#refresh')
  await page.waitForFunction(()=>document.querySelector('#state')?.textContent==='checking')
  await page.click('#logout')
  await page.evaluate(()=>window.customerAccountTest.resolveRestore())
  await page.waitForFunction(()=>document.querySelector('#state')?.textContent==='guest')
  check(await page.locator('#order-name').inputValue()==='Already typed','order field erased')
  await page.click('#signin')
  await page.getByLabel('Email address').fill('customer@example.test')
  await page.getByRole('button',{name:'Continue with Email'}).click()
  await page.getByLabel('6-digit verification code').fill('123456')
  await page.getByRole('button',{name:'Verify code'}).click()
  await page.evaluate(()=>window.customerAccountTest.invalidate())
  await page.evaluate(()=>window.customerAccountTest.resolveVerify())
  await page.waitForFunction(()=>document.querySelector('#state')?.textContent!=='checking')
  check(await page.locator('#state').textContent()==='guest','stale OTP accepted after auth change')
  check(await page.locator('dialog[open]').count()===1,'stale OTP closed current sign-in intent')
  await page.getByRole('button',{name:'Verify code'}).click()
  await page.evaluate(()=>window.customerAccountTest.switchIdentity())
  await page.waitForFunction(()=>document.querySelector('#state')?.textContent==='authenticated:customer-b')
  await page.evaluate(()=>window.customerAccountTest.resolveVerify())
  await page.waitForFunction(()=>document.querySelector('#state')?.textContent==='authenticated:customer-b')
  check(await page.locator('dialog[open]').count()===1,'focus restored B but late OTP A was accepted')
  await page.goto('http://localhost:4173/tests/fixtures/customer-account/ui.html')
  await page.waitForFunction(()=>document.querySelector('#state')?.textContent==='guest')
  await page.setViewportSize({width:390,height:844})
  await page.click('#signin')
  await page.getByRole('button',{name:'Continue with Google'}).click()
  await page.getByText('Sign in could not be completed. Try again or continue as a guest.').waitFor()
  check(await page.getByRole('button',{name:'Continue as Guest'}).isEnabled(),'guest disabled after auth error')
  await page.keyboard.press('Escape')
  check(await page.locator('#signin').evaluate(element=>element===document.activeElement),'dialog focus not returned')
  await page.evaluate(()=>document.documentElement.lang='ko')
  await page.click('#signin')
  await page.getByRole('button',{name:'이메일로 계속'}).waitFor()
  await page.getByLabel('이메일 주소').fill('customer@example.test')
  await page.getByRole('button',{name:'이메일로 계속'}).click()
  check(await page.getByRole('button',{name:/초 후 재전송/}).isDisabled(),'OTP cooldown not enforced')
  const before=await page.evaluate(()=>window.customerAccountTest.counts().calls)
  await page.getByRole('button',{name:'인증번호 확인'}).click()
  check(await page.evaluate(()=>window.customerAccountTest.counts().calls)===before,'empty OTP submitted')
  await page.getByLabel('6자리 인증번호').fill('123456')
  await page.getByRole('button',{name:'인증번호 확인'}).click()
  check(await page.getByRole('button',{name:'Google로 계속'}).isDisabled(),'concurrent auth enabled')
  await page.getByRole('button',{name:'비회원으로 계속'}).click()
  await page.evaluate(()=>window.customerAccountTest.resolveVerify())
  check(await page.locator('#order-name').inputValue()==='Already typed','guest lost form')
  check(pageErrors.length===0,JSON.stringify(pageErrors))
  return {provider:'disabled/readiness/logout/delayed OTP/focus/KO/cooldown/error/guest passed',browser:page.context().browser().version(),pageErrors:pageErrors.length}
}
